export function tabs(items, active, onChange) {
  const bar = h('div', { class: 'tabs', role: 'tablist' });
  items.forEach(([id, label]) => bar.append(h('button', { role: 'tab', class: 'tab' + (id === active ? ' on' : ''), 'aria-selected': id === active, onclick: () => { onChange(id); } }, label)));
  return bar;
}
