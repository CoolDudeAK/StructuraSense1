export function table(cols, rows, { empty: emptyMsg = 'Nothing to show yet.' } = {}) {
  if (!rows.length) return empty(emptyMsg);
  return h('div', { class: 'tbl-wrap' }, h('table', { class: 'tbl' },
    h('thead', null, h('tr', null, cols.map(c => h('th', { class: c.cls }, c.label)))),
    h('tbody', null, rows.map(r => h('tr', null, cols.map(c => h('td', { class: c.cls, 'data-label': c.label }, c.render ? c.render(r) : r[c.key])))))));
}
export function download(name, text, type = 'text/csv') {
  const a = h('a', { href: URL.createObjectURL(new Blob([text], { type })), download: name }); document.body.append(a); a.click(); a.remove();
}
export function debounce(fn, ms = 300) { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; }
