export const fmt = {
  n(v, d = 1) { return v == null || isNaN(v) ? '—' : Number(v).toFixed(d); },
  int(v) { return v == null ? '—' : Math.round(v).toLocaleString('en-IN'); },
  time(ms) { return ms ? new Date(ms).toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', second: '2-digit' }) : '—'; },
  hm(ms) { return ms ? new Date(ms).toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', hour12: false }) : '—'; },
  dh(ms) { return ms ? new Date(ms).toLocaleString('en-IN', { day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit', hour12: false }) : '—'; },
  dt(ms) { return ms ? new Date(ms).toLocaleString('en-IN', { day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit' }) : '—'; },
  ago(ms) {
    if (!ms) return 'never';
    const s = Math.max(0, (Date.now() - ms) / 1000);
    if (s < 10) return 'just now'; if (s < 90) return Math.round(s) + ' s ago';
    if (s < 5400) return Math.round(s / 60) + ' min ago'; if (s < 129600) return Math.round(s / 3600) + ' h ago';
    return Math.round(s / 86400) + ' d ago';
  },
  inr(v) { return v == null ? '—' : '₹' + Math.round(v).toLocaleString('en-IN'); },
};

export function bandClass(score) {
  if (score == null) return 'b-none';
  return score >= 80 ? 'b-ok' : score >= 60 ? 'b-watch' : score >= 40 ? 'b-warn' : 'b-crit';
}
export const bandLabel = (score) => score == null ? 'No data' : score >= 80 ? 'Optimal' : score >= 60 ? 'Routine check' : score >= 40 ? 'Inspection needed' : 'Urgent action';

