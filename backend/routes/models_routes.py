@bp.post("/models/<mid>/retrain")
@auth.require("admin")
def retrain(mid):
    name = {"vibration_anomaly": "autoencoder", "health_index": "health_forest", "load_regression": "load_regression"}.get(mid)
    if not name:
        return fail("not_retrainable", "This model has nothing to retrain.", 400)
    ml.retrain(name)
    db.audit(auth.current_user(), "model.retrain", "model", mid)
    return jsonify({"ok": True})
